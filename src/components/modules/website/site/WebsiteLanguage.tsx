const WebsiteLanguageContext = createContext<WebsiteLanguage>('id');

export function WebsiteLanguageProvider({
  language,
  children
}: {
  language: WebsiteLanguage;
  children: ReactNode;
}) {
  return <WebsiteLanguageContext.Provider value={language}>{children}</WebsiteLanguageContext.Provider>;
}

export function useWebsiteLanguage(): WebsiteLanguage {
  return useContext(WebsiteLanguageContext);
}

export function translateWebsiteUi(text: string, language: WebsiteLanguage): string {
  return language === 'en' ? translations[text] ?? text : text;
}
